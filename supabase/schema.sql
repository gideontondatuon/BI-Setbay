-- BI SETBAY schema. Jalankan di Supabase SQL Editor.
-- Tabel sengaja TIDAK memiliki kolom BANK_ACCOUNT untuk kepatuhan privasi & kerahasiaan perbankan.

create table if not exists public.setbay_transactions (
  id bigint generated by default as identity primary key,
  source text not null check (source in ('SETBAY MANADO', 'SETBAY KASTIP')),
  transaction_date date not null,
  transaction_type text not null default '',
  money_type text not null default '',
  bank_name text not null default '',
  branch_name text not null default '',
  denom text not null default '',
  pieces numeric not null default 0,
  amount numeric not null default 0,
  inflow numeric not null default 0,
  outflow numeric not null default 0,
  netflow numeric not null default 0,
  created_at timestamptz not null default now()
);

-- Indeks untuk mempercepat pembacaan, filtering, dan agregasi data analitik
create index if not exists setbay_tx_date_idx on public.setbay_transactions(transaction_date);
create index if not exists setbay_tx_source_idx on public.setbay_transactions(source);
create index if not exists setbay_tx_bank_idx on public.setbay_transactions(bank_name);
create index if not exists setbay_tx_type_idx on public.setbay_transactions(transaction_type);
create index if not exists setbay_tx_source_date_idx on public.setbay_transactions(source, transaction_date desc);

-- Aktifkan Row Level Security (RLS)
alter table public.setbay_transactions enable row level security;

-- Kebijakan 1: Pembacaan data analitik (SELECT) dapat diakses publik (anon & authenticated)
drop policy if exists "public read setbay transactions" on public.setbay_transactions;
create policy "public read setbay transactions" on public.setbay_transactions 
  for select to anon, authenticated using (true);

-- Kebijakan 2: Penyisipan data baru (INSERT) hanya diperbolehkan bagi pengguna terautentikasi (Admin)
drop policy if exists "authenticated insert setbay transactions" on public.setbay_transactions;
create policy "authenticated insert setbay transactions" on public.setbay_transactions 
  for insert to authenticated with check (true);

-- Kebijakan 3: Pembaruan data (UPDATE) hanya untuk admin terautentikasi
drop policy if exists "authenticated update setbay transactions" on public.setbay_transactions;
create policy "authenticated update setbay transactions" on public.setbay_transactions 
  for update to authenticated using (true) with check (true);

-- Kebijakan 4: Penghapusan data (DELETE) hanya untuk admin terautentikasi (untuk re-import sheet)
drop policy if exists "authenticated delete setbay transactions" on public.setbay_transactions;
create policy "authenticated delete setbay transactions" on public.setbay_transactions 
  for delete to authenticated using (true);
